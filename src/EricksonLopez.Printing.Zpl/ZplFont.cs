namespace EricksonLopez.Printing.Zpl;

/// <summary>
/// Specifies standard built-in Zebra alphanumeric font identifiers.
/// </summary>
public enum ZplFont
{
    /// <summary>
    /// Specifies the scalable smooth font 0 (<c>^A0</c>).
    /// </summary>
    Font0 = '0',

    /// <summary>
    /// Specifies standard alphanumeric bitmap font A (<c>^AA</c>).
    /// </summary>
    FontA = 'A',

    /// <summary>
    /// Specifies standard alphanumeric bitmap font B (<c>^AB</c>).
    /// </summary>
    FontB = 'B',

    /// <summary>
    /// Specifies standard alphanumeric bitmap font C (<c>^AC</c>).
    /// </summary>
    FontC = 'C',

    /// <summary>
    /// Specifies standard alphanumeric bitmap font D (<c>^AD</c>).
    /// </summary>
    FontD = 'D',

    /// <summary>
    /// Specifies standard alphanumeric bitmap font E (<c>^AE</c>).
    /// </summary>
    FontE = 'E',

    /// <summary>
    /// Specifies standard alphanumeric bitmap font F (<c>^AF</c>).
    /// </summary>
    FontF = 'F',

    /// <summary>
    /// Specifies standard alphanumeric bitmap font G (<c>^AG</c>).
    /// </summary>
    FontG = 'G',

    /// <summary>
    /// Specifies standard alphanumeric bitmap font H (<c>^AH</c>).
    /// </summary>
    FontH = 'H'
}
